import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { join } from 'node:path';
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:13000';
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}), args: ['--no-sandbox'] });
const suffix = Date.now().toString();
try {
  const a = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  const page = await a.newPage();
  await page.goto(`${base}/register`);
  await page.getByLabel('Nom de l’espace').fill('Boutique A');
  await page.getByLabel('Email').fill(`alice${suffix}@example.com`);
  await page.getByLabel('Mot de passe').fill('long-test-password-A');
  await page.getByRole('button', { name: 'Créer mon compte' }).click();
  await page.waitForURL('**/dashboard');
  assert.match(await page.locator('main').innerText(), /Indisponibles/);
  await page.getByRole('link', { name: 'Brouillons', exact: true }).click();
  await page.getByLabel('Texte').fill('Brouillon privé A');
  await page.getByRole('button', { name: 'Enregistrer le brouillon' }).click();
  await page.getByLabel('Modifier le texte').waitFor();
  await page.getByLabel('Modifier le texte').fill('Brouillon modifié A');
  await Promise.all([page.waitForResponse(r => r.request().method() === 'POST' && r.url().includes('/drafts')), page.getByRole('button', { name: 'Enregistrer les modifications' }).click()]);
  await page.reload();
  assert.equal(await page.getByLabel('Modifier le texte').inputValue(), 'Brouillon modifié A');
  if (process.env.SCREENSHOT_DIR) await page.screenshot({ path: join(process.env.SCREENSHOT_DIR, 'marketing-drafts-desktop.png'), fullPage: true });
  const b = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const mobile = await b.newPage();
  await mobile.goto(`${base}/register`);
  await mobile.getByLabel('Nom de l’espace').fill('Boutique B');
  await mobile.getByLabel('Email').fill(`bob${suffix}@example.com`);
  await mobile.getByLabel('Mot de passe').fill('long-test-password-B');
  await mobile.getByRole('button', { name: 'Créer mon compte' }).click();
  await mobile.waitForURL('**/dashboard');
  await mobile.getByRole('link', { name: 'Brouillons', exact: true }).click();
  await mobile.waitForURL('**/drafts');
  assert.equal(await mobile.getByText('Brouillon modifié A').count(), 0);
  assert.match(await mobile.locator('main').innerText(), /Aucun brouillon/);
  if (process.env.SCREENSHOT_DIR) await mobile.screenshot({ path: join(process.env.SCREENSHOT_DIR, 'marketing-drafts-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Supprimer le brouillon' }).click();
  await page.getByText('Aucun brouillon pour le moment.').waitFor();
  await page.getByRole('button', { name: 'Déconnexion' }).click();
  await page.waitForURL('**/login');
  await page.getByLabel('Email').fill(`alice${suffix}@example.com`);
  await page.getByLabel('Mot de passe').fill('long-test-password-A');
  await page.getByRole('button', { name: 'Se connecter' }).click();
  await page.waitForURL('**/dashboard');
  console.log('E2E passed: registration, sign-in/out, drafts, tenant isolation, desktop and mobile.');
  await a.close(); await b.close();
} finally { await browser.close(); }
